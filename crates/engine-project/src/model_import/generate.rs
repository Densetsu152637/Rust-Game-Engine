use super::*;
use crate::{
    Scene, Transform,
    content::{Mesh, Vertex},
};
use engine_assets::{AlphaMode, ChannelValues, ImportedScene, Interpolation};
use serde_json::{Value, json};
use std::collections::BTreeMap;

pub(super) struct Generated {
    pub assets: Vec<Asset>,
    pub warnings: Vec<String>,
}
struct Output<'a> {
    project: &'a Project,
    prefix: &'a str,
    relative: &'a Path,
    staging: &'a Path,
    assets: Vec<Asset>,
    bytes: u64,
}
impl Output<'_> {
    fn add(&mut self, suffix: &str, filename: &str, kind: &str) -> Result<()> {
        let id = format!("{}:{suffix}", self.prefix);
        if self.project.assets.contains_key(&id) {
            return Err(Error::new(
                "asset.import.id_exists",
                format!("Asset ID already exists: {id}"),
            ));
        }
        if self.assets.len() + self.project.assets.len() >= 65536 || self.assets.len() >= 4096 {
            return Err(Error::new(
                "asset.import.limit",
                "Generated asset count exceeds capacity",
            ));
        }
        self.bytes = self
            .bytes
            .checked_add(std::fs::metadata(self.staging.join(filename))?.len())
            .ok_or_else(|| Error::new("asset.import.limit", "Generated bytes overflow"))?;
        if self.bytes > 512 * 1024 * 1024 {
            return Err(Error::new(
                "asset.import.limit",
                "Generated assets exceed 512 MiB",
            ));
        }
        self.assets.push(Asset {
            id,
            path: self.relative.join(filename),
            kind: kind.into(),
        });
        Ok(())
    }
    fn json(
        &mut self,
        suffix: &str,
        filename: &str,
        kind: &str,
        value: &impl serde::Serialize,
        maximum: usize,
    ) -> Result<()> {
        transaction::json_file(&self.staging.join(filename), value, maximum)?;
        self.add(suffix, filename, kind)
    }
}
pub(super) fn generate(
    project: &Project,
    scene: &ImportedScene,
    prefix: &str,
    relative: &Path,
    staging: &Path,
) -> Result<Generated> {
    let mut output = Output {
        project,
        prefix,
        relative,
        staging,
        assets: Vec::new(),
        bytes: 0,
    };
    let mut warnings=vec!["Rendering uses metallic-roughness PBR, base-color and data textures, smooth normals and alpha blending. Tangent frames are reconstructed from UV derivatives. Emissive/occlusion maps, alpha masking and cubic TRS animation remain preserved in the model asset.".into()];
    let node_entities: Vec<_> = (0..scene.nodes.len())
        .map(|i| format!("node:{i}"))
        .collect();
    let binding_bytes = serde_json::to_vec(&node_entities)?.len();
    let mut entity_count = 1 + scene.nodes.len();
    let mut skin_binding_bytes = 0_usize;
    for node in &scene.nodes {
        if let Some(mesh) = node.mesh {
            let primitives = scene.meshes[mesh].primitives.len();
            entity_count = entity_count
                .checked_add(primitives)
                .ok_or_else(|| Error::new("asset.import.limit", "Prefab entity count overflow"))?;
            if node.skin.is_some() {
                if scene.nodes.len() > 4096 || binding_bytes > 60 * 1024 {
                    return Err(Error::new(
                        "asset.import.skin.limit",
                        "Skin bindings require at most 4096 nodes and a bounded binding component",
                    ));
                }
                skin_binding_bytes = primitives
                    .checked_mul(binding_bytes)
                    .and_then(|n| skin_binding_bytes.checked_add(n))
                    .ok_or_else(|| {
                        Error::new(
                            "asset.import.skin.limit",
                            "Skin binding byte count overflow",
                        )
                    })?;
            }
        }
    }
    if entity_count > 65536 || skin_binding_bytes > 8 * 1024 * 1024 {
        return Err(Error::new(
            "asset.import.limit",
            "Prefab entity or aggregate skin-binding capacity exceeded",
        ));
    }
    #[derive(Serialize)]
    struct ModelReference<'a> {
        version: u32,
        scene: &'a ImportedScene,
        node_entities: &'a [String],
    }
    let model = ModelReference {
        version: 1,
        scene,
        node_entities: &node_entities,
    };
    output.json("model", "model.json", "model", &model, 256 * 1024 * 1024)?;
    for (i, image) in scene.images.iter().enumerate() {
        let filename = format!("image-{i}.png");
        image::save_buffer_with_format(
            staging.join(&filename),
            &image.rgba8,
            image.width,
            image.height,
            image::ColorType::Rgba8,
            image::ImageFormat::Png,
        )
        .map_err(|e| Error::new("asset.import.image", e.to_string()))?;
        output.add(&format!("texture:{i}"), &filename, "texture")?;
    }
    for (mesh_index, mesh) in scene.meshes.iter().enumerate() {
        for (primitive_index, primitive) in mesh.primitives.iter().enumerate() {
            let material = primitive.material.map(|i| &scene.materials[i]);
            let texture_refs: Vec<_> = material
                .into_iter()
                .flat_map(|m| {
                    [
                        m.base_color_texture,
                        m.metallic_roughness_texture,
                        m.normal_texture,
                    ]
                })
                .flatten()
                .collect();
            let uv_set = texture_refs.first().map_or(0, |t| t.tex_coord);
            if texture_refs.iter().any(|t| t.tex_coord != uv_set) {
                return Err(Error::new(
                    "asset.import.uv",
                    "Material textures must share one UV set",
                ));
            }
            if uv_set > 1 {
                return Err(Error::new(
                    "asset.import.uv",
                    "Renderer supports shared texture coordinates 0 or 1",
                ));
            }
            let mesh = Mesh {
                normals: primitive
                    .vertices
                    .iter()
                    .map(|v| v.normal.unwrap_or([0.0; 3]))
                    .collect(),
                vertices: primitive
                    .vertices
                    .iter()
                    .map(|v| Vertex {
                        position: v.position,
                        uv: if uv_set == 1 { v.uv1 } else { v.uv0 }.unwrap_or([0.0; 2]),
                        color: v.color.unwrap_or([1.0; 4]),
                    })
                    .collect(),
                indices: primitive.indices.clone(),
            };
            output.json(
                &format!("mesh:{mesh_index}:{primitive_index}"),
                &format!("mesh-{mesh_index}-{primitive_index}.json"),
                "mesh",
                &mesh,
                64 * 1024 * 1024,
            )?;
        }
    }
    let mut entities =
        vec![json!({"id":"root","name":prefix,"components":{"Transform":{"position":[0,0,0]}}})];
    for (node_index, node) in scene.nodes.iter().enumerate() {
        let transform = Transform {
            version: 1,
            position: node.transform.translation,
            rotation: node.transform.rotation,
            scale: node.transform.scale,
        };
        let actual = crate::transforms::local_matrix(&transform)?.to_cols_array_2d();
        if actual
            .iter()
            .flatten()
            .zip(node.matrix.iter().flatten())
            .any(|(a, b)| (a - b).abs() > 1e-4 * (1.0 + b.abs()))
        {
            return Err(Error::new(
                "asset.import.transform",
                "Matrix cannot be represented faithfully by authored TRS",
            ));
        }
        entities.push(json!({"id":node_entities[node_index],"name":node.name.as_deref().filter(|name| !name.is_empty() && name.len() <= 256 && !name.chars().any(char::is_control)).unwrap_or("Node"),
            "parent":node.parent.map(|i|node_entities[i].as_str()).unwrap_or("root"),"components":{"Transform":transform}}));
        if let Some(mesh_index) = node.mesh {
            for (primitive_index, primitive) in
                scene.meshes[mesh_index].primitives.iter().enumerate()
            {
                let material = primitive.material.map(|i| &scene.materials[i]);
                let texture = material
                    .and_then(|m| m.base_color_texture)
                    .map(|t| format!("{prefix}:texture:{}", scene.textures[t.texture].image));
                let mut entity = json!({"id":format!("node:{node_index}:primitive:{primitive_index}"),"name":format!("Primitive {primitive_index}"),"parent":node_entities[node_index],
                "components":{"Transform":{"position":[0,0,0]},"MeshRenderer":{"mesh":format!("{prefix}:mesh:{mesh_index}:{primitive_index}"),"texture":texture},
                "MeshMaterial":{"version":1,"texture":texture,"tint":material.map_or([1.0;4],|m|m.base_color),"metallic":material.map_or(1.0,|m|m.metallic),"roughness":material.map_or(1.0,|m|m.roughness),
                "metallic_roughness_texture":material.and_then(|m|m.metallic_roughness_texture).map(|t|format!("{prefix}:texture:{}",scene.textures[t.texture].image)),
                "normal_texture":material.and_then(|m|m.normal_texture).map(|t|format!("{prefix}:texture:{}",scene.textures[t.texture].image)),"normal_scale":material.map_or(1.0,|m|m.normal_scale),
                "unlit":false,"transparent":material.is_some_and(|m|m.alpha_mode==AlphaMode::Blend)}}});
                if node.skin.is_some() {
                    entity["components"]["custom"] = json!({"engine.SkinBinding":{"version":1,"data":{
                        "model":format!("{prefix}:model"),"mesh_node":node_index,"primitive":primitive_index,"bindings":node_entities
                    }}});
                }
                if scene
                    .morphs
                    .primitives
                    .iter()
                    .any(|m| m.mesh == mesh_index && m.primitive == primitive_index)
                {
                    if entity["components"].get("custom").is_none() {
                        entity["components"]["custom"] = json!({});
                    }
                    entity["components"]["custom"]["engine.MorphWeights"] = json!({"version":1,"data":{"model":format!("{prefix}:model"),"mesh_node":node_index,"primitive":primitive_index,"weights":[]}});
                    if let Some(clip) = scene.clips.iter().position(|c| {
                        c.channels.iter().any(|c| {
                            c.target_node == node_index
                                && matches!(c.values, ChannelValues::Weights(_))
                        })
                    }) {
                        entity["components"]["custom"]["engine.MorphPlayer"] = json!({"version":1,"data":{"clip":clip,"time":0.,"speed":1.,"looping":true,"playing":true}});
                    }
                }
                entities.push(entity);
            }
        }
    }
    let mut first_clip = None;
    let mut skipped = 0;
    for (index, clip) in scene.clips.iter().enumerate() {
        if scene.nodes.is_empty()
            || scene.nodes.len() > 4096
            || binding_bytes > 60 * 1024
            || clip.channels.iter().any(|c| {
                c.interpolation == Interpolation::CubicSpline
                    && !matches!(c.values, ChannelValues::Weights(_))
            })
        {
            skipped += 1;
            continue;
        }
        let mut tracks: BTreeMap<usize, Value> = BTreeMap::new();
        for channel in &clip.channels {
            if matches!(channel.values, ChannelValues::Weights(_)) {
                continue;
            }
            let track = tracks
                .entry(channel.target_node)
                .or_insert_with(|| json!({"joint":channel.target_node}));
            let (property, values) = match &channel.values {
                ChannelValues::Translation(v) => ("translation", json!(v)),
                ChannelValues::Rotation(v) => ("rotation", json!(v)),
                ChannelValues::Scale(v) => ("scale", json!(v)),
                ChannelValues::Weights(_) => continue,
            };
            track[property] = json!({"times":channel.times,"values":values,"interpolation":if channel.interpolation==Interpolation::Step {"step"} else {"linear"}});
        }
        let suffix = format!("animation:{index}");
        let value = json!({"version":1,"duration":clip.duration,"joints":scene.nodes.len(),"tracks":tracks.into_values().collect::<Vec<_>>(),"events":[]});
        output.json(
            &suffix,
            &format!("animation-{index}.json"),
            "animation",
            &value,
            16 * 1024 * 1024,
        )?;
        if first_clip.is_none() {
            first_clip = Some(format!("{prefix}:{suffix}"));
        }
    }
    if let Some(clip) = first_clip {
        entities[0]["components"]["custom"] = json!({"engine.AnimationPlayer":{"version":1,"data":{"clip":clip,"looping":true,"speed":1.0,"bindings":node_entities}}});
    }
    if skipped > 0 {
        warnings.push(format!("{skipped} clips preserved only in model metadata: runtime supports step/linear clips with at most 4096 nodes and a 64 KiB binding component."));
    }
    if scene.scenes.len() > 1 {
        warnings.push("Prefab includes every source node; original scene root selections remain in model metadata.".into());
    }
    if entities.len() > 65536 {
        return Err(Error::new(
            "asset.import.limit",
            "Generated prefab exceeds 65536 entities",
        ));
    }
    let prefab = json!({"schema":1,"scene_id":format!("{prefix}:prefab"),"entities":entities});
    // Typed loading verifies the exact authoring contract, including material fields.
    let typed: Scene = serde_json::from_value(prefab)?;
    typed.validate()?;
    output.json("prefab", "prefab.json", "prefab", &typed, 16 * 1024 * 1024)?;
    Ok(Generated {
        assets: output.assets,
        warnings,
    })
}
